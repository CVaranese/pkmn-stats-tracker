# copied from agent-habits 0.10.2 (plugins/agent-habits/scripts/tasks.py); refresh with the habits-update skill
"""Rebuild the generated parts of the task tracker from the task files themselves.

Config: `.claude/habits.json` key "tasks" (all optional, these are the defaults):
    {"dir": "docs/tasks", "prefix": "T-", "plan": "PLAN.md", "index": "README.md", "done": "done"}
plan / index / done are relative to dir; the closed list is <done>/<index>. A project without a plan file just has
no lanes and no plan board.

An open task (<dir>/<prefix><n>-<slug>.md, first line `# <prefix><n>: <title>`) carries:
    **Status:** open | started | blocked [(note)]    (any case; the Status of a task in <done>/ is ignored)
    **Needs you:** <question for the user>          (only while one is open; required when blocked)
    **Priority:** P0 | P1 | P2 | P3 [(note)]         (optional; once any open task has one, every open task needs one)
    **Links:** [text](url), [text](url)              (optional: Jira / Rally / GitHub issues, outside docs)
Its "Written" date comes from a `## State when written (YYYY-MM-DD)` heading, else "—".
A closed task (<dir>/<done>/) ends with a `## Resolution` section: the date in its heading (else its first date) is
the closed date (undated ones list last), its first line the summary. With "review_since": "YYYY-MM-DD" in the
config, a task closed on or after that date also needs a review line in its Resolution (`Review: <link / result>`
or `Review findings: ...`; no review run = `Review: none (<why>)`), so every close records its code review.
The plan orders the open tasks in one of two ways (both hand-kept):
- a queue: a paragraph starting `Order:` (outside the board) listing task ids; the board sorts the open tasks by
  Priority, then by their place in that list, then by number (one task at a time, first = next to run);
- lanes: the plan's tables under `### ` headings, first column the lane name, second its task ids in order.

The task files are the one place a status, priority, question, decision or resolution is written. This script copies
them into the blocks between the <!-- board: ... --> and <!-- /board --> markers: the index table (index file), the
plan's board (waiting on you, then the queue or each lane's open tasks in order) and the closed list
(<done>/<index>).

    python -I tools/tasks.py           rewrite the blocks
    python -I tools/tasks.py --check   exit 1 if a block is stale, a task header is missing / wrong, a plan
                                       lane or Order list names a closed or unknown task, a close since
                                       review_since has no review line, or a link to a task file is missing
                                       (in the task folder's markdown and habits.json trackers.lists files;
                                       a closed task moved into done/ and a link kept its old path)
    python -I tools/tasks.py --next    print what's next (waiting on you, the first 3 of the queue or each lane's
                                       first task); writes nothing
    --project DIR                      the project root (default: the folder above this script holding
                                       .claude/habits.json or .git)
"""
import json
import os
import re
import sys
from pathlib import Path

DEFAULTS = {"dir": "docs/tasks", "prefix": "T-", "plan": "PLAN.md", "index": "README.md", "done": "done"}
START = re.compile(r"<!-- board:[^>]*-->")
END = "<!-- /board -->"
NEW_START = "<!-- board: generated by tools/tasks.py, edit the task files -->"
STATES = ("open", "started", "blocked")
PRIORITIES = ("P0", "P1", "P2", "P3")
ORDER = re.compile(r"^Order:(.*(?:\n(?!\s*\n).*)*)", re.M)
DATE = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")
LINK = re.compile(r"\]\(([^)\s]+)\)")
SUMMARY_LEN = 160
# `Review: ...` / `- **Review findings:** ...` / `**Review** (/code-review on abc123): ...` at a line start, with
# something after the colon (not the review queue)
REVIEW_LINE = re.compile(r"^[\s\-*]*(?:\*\*)?(?:code[ -])?reviews?\b(?! ?queue)[^:\n]{0,60}:(?:\*\*)?\s*\S", re.M | re.I)


def project_root(argv):
    if "--project" in argv:
        i = argv.index("--project") + 1
        if i >= len(argv) or argv[i].startswith("--"):
            print("usage: tasks.py [--check] [--project DIR]", file=sys.stderr)
            sys.exit(2)
        return Path(argv[i]).resolve()
    here = Path(__file__).resolve().parent
    for d in (here, *here.parents):
        if (d / ".claude" / "habits.json").is_file() or (d / ".git").exists():
            return d
    return here.parent


def config(root):
    try:
        cfg = json.loads((root / ".claude" / "habits.json").read_text(encoding="utf-8")).get("tasks") or {}
    except (OSError, ValueError):
        cfg = {}
    return {**DEFAULTS, **cfg}


def header(text, name):
    m = re.search(rf"^\*\*{name}:\*\* (.+)$", text, re.M)
    return m.group(1).strip() if m else ""


class Board:
    def __init__(self, root, cfg):
        self.prefix = cfg["prefix"]
        self.dir = root / cfg["dir"]
        self.index = self.dir / cfg["index"]
        self.plan = self.dir / cfg["plan"] if cfg.get("plan") else None
        self.done = self.dir / cfg["done"]
        self.done_list = self.done / cfg["index"]
        p = re.escape(self.prefix)
        self.file_re = re.compile(rf"^{p}(\d+)-.*\.md$")
        self.title_re = re.compile(rf"^# {p}\d+: (.+)$", re.M)
        self.id_re = re.compile(rf"(?<![\w-]){p}\d+\b")

    def files(self, folder):
        out = []
        for f in folder.glob("*.md") if folder.is_dir() else ():
            m = self.file_re.match(f.name)
            if m:
                out.append((int(m.group(1)), f))
        return sorted(out, key=lambda x: x[0])

    def open_tasks(self):
        """[{id, file, title, status, state, priority, needs, links, written}] by number; problems."""
        out, problems = [], []
        for n, p in self.files(self.dir):
            text = p.read_text(encoding="utf-8")
            title = self.title_re.search(text)
            status, needs = header(text, "Status"), header(text, "Needs you")
            written = re.search(r"^## State when written \((20\d\d-\d\d-\d\d)", text, re.M)
            state = re.split(r"[\s(]", status, 1)[0].lower() if status else None
            if not status:
                problems.append(f"{p.name}: no '**Status:** {' | '.join(STATES)}' line (a closed task moves to "
                                f"{self.done.name}/)")
            elif state not in STATES:
                problems.append(f"{p.name}: Status '{status}' is not {' | '.join(STATES)} (a closed task moves to "
                                f"{self.done.name}/)")
            elif state == "blocked" and not needs:
                problems.append(f"{p.name}: blocked but no '**Needs you:**' line saying what for")
            priority = header(text, "Priority")
            prio = re.split(r"[\s(]", priority, 1)[0].upper() if priority else ""
            if priority and prio not in PRIORITIES:
                problems.append(f"{p.name}: Priority '{priority}' is not {' | '.join(PRIORITIES)}")
            out.append({"id": f"{self.prefix}{n}", "file": p.name, "title": title.group(1) if title else p.stem,
                        "status": status or "?", "state": state, "priority": prio if prio in PRIORITIES else "",
                        "needs": needs, "links": header(text, "Links"),
                        "written": written.group(1) if written else "—"})
        if any(t["priority"] for t in out):
            problems += [f"{t['file']}: no '**Priority:** {' | '.join(PRIORITIES)}' line (the other open tasks "
                         f"have one)" for t in out if not t["priority"]]
        return out, problems

    def closed_tasks(self):
        out = []
        for n, p in self.files(self.done):
            text = p.read_text(encoding="utf-8")
            title = self.title_re.search(text)
            closed, summary = resolution(text)
            res = re.search(r"^## Resolution\b.*", text, re.M | re.S)
            out.append({"id": f"{self.prefix}{n}", "n": n, "file": p.name,
                        "title": title.group(1) if title else p.stem, "closed": closed, "summary": summary,
                        "reviewed": bool(res and REVIEW_LINE.search(res.group(0)))})
        return sorted(out, key=lambda t: (t["closed"] != "—", t["closed"], t["n"]), reverse=True)

    def lanes(self, plan):
        """[(lane, [ids])] from the plan's tables under `### ` headings: first column the lane, second its ids."""
        out = []
        for part in re.split(r"^(?=### )", plan, flags=re.M):
            if not part.startswith("### "):
                continue
            for first, ids in re.findall(r"^\| ?([^|]+?) ?\| ?([^|]*)\|", part, re.M):
                if first.lower() != "lane" and not set(first) <= set("-: "):
                    out.append((first.strip(), self.id_re.findall(ids)))
        return out

    def broken_links(self, root, extra):
        """Links to a task file that isn't there (a closed task moved into done/ and a link kept its old path), in
        the task folder's markdown and the `extra` files (trackers.lists)."""
        out = []
        found = {p.name: p for _, p in self.files(self.dir) + self.files(self.done)}
        for src in sorted({*self.dir.rglob("*.md"), *(root / e for e in extra)}):
            if not src.is_file():
                continue
            for target in LINK.findall(src.read_text(encoding="utf-8")):
                path = target.split("#")[0]
                name = path.rsplit("/", 1)[-1]
                if "://" in path or not self.file_re.match(name) or (src.parent / path).is_file():
                    continue
                hint = (f" (now {os.path.relpath(found[name], src.parent).replace(os.sep, '/')})"
                        if name in found else "")
                out.append(f"{src.relative_to(root).as_posix()}: link to {path} is missing{hint}")
        return out

    def order(self, plan):
        """The queue's hand-kept order: ids in the plan's `Order:` paragraph outside the board; None without one."""
        m = START.search(plan)
        e = plan.find(END, m.end()) if m else -1
        outside = plan[:m.start()] + plan[e + len(END):] if m and e >= 0 else plan
        o = ORDER.search(outside)
        return list(dict.fromkeys(self.id_re.findall(o.group(1)))) if o else None


def plain(line):
    """A Resolution line as plain table text: no list marker, emphasis, link targets, leading date or labels."""
    line = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", line)
    line = re.sub(r"\*\*|`|\b(Date|Outcome):", "", line)
    line = re.sub(r"^[\s\-*.,;:]*(Closed\b)?[\s.,;:]*(20\d\d-\d\d-\d\d)?[\s.,;:]*", "", line)
    return re.sub(r"\s+", " ", line).rstrip()


def resolution(text):
    """(closed date, summary) from a closed task's Resolution section; ("—", "—") without one."""
    m = re.search(r"^## Resolution\b([^\n]*)\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        return "—", "—"
    date = DATE.search(m.group(1)) or DATE.search(m.group(2))
    summary = next((s for s in map(plain, m.group(2).splitlines()) if s), "—")
    if len(summary) > SUMMARY_LEN:
        summary = summary[:SUMMARY_LEN].rsplit(" ", 1)[0] + " …"
    return (date.group(1) if date else "—"), summary


def cell(s):
    return s.replace("|", "\\|")


def index_block(ts):
    prio = any(t["priority"] for t in ts)
    rows = ["| ID | Task | Status |" + (" Priority |" if prio else "") + " Written | Needs you |",
            "|---|---|---|" + ("---|" if prio else "") + "---|---|"]
    for t in ts:
        task = cell(t["title"]) + (f" · {cell(t['links'])}" if t["links"] else "")
        rows.append(f"| [{t['id']}]({t['file']}) | {task} | {cell(t['status'])} |"
                    + (f" {t['priority'] or '—'} |" if prio else "")
                    + f" {t['written']} | {cell(t['needs']) or '—'} |")
    return "\n".join(rows)


def queue(ts, order):
    """The open tasks in run order: Priority (none last), place in the plan's Order list (unlisted last), number."""
    pos = {i: k for k, i in enumerate(order or [])}
    rank = {p: k for k, p in enumerate(PRIORITIES)}
    return sorted(ts, key=lambda t: (rank.get(t["priority"], len(rank)), pos.get(t["id"], len(pos)),
                                     int(re.sub(r"\D", "", t["id"]) or 0)))


def plan_block(b, ts, plan, link_dir):
    by_id = {t["id"]: t for t in ts}
    lines = [f"**Waiting on you** (answer in chat, e.g. \"{b.prefix}12: yes\"; the session records it in the task):"]
    lines += [f"- [{t['id']}]({link_dir}{t['file']}) {t['needs']}" for t in ts if t["needs"]] or ["- nothing"]
    order = b.order(plan)
    if order is not None:
        lines += ["", "**Queue** (one task at a time; first = next to run):", "",
                  "| # | Priority | ID | Task | Status |", "|---|---|---|---|---|"]
        lines += [f"| {k} | {t['priority'] or '—'} | [{t['id']}]({link_dir}{t['file']}) | {cell(t['title'])} | "
                  f"{cell(t['status'])} |" for k, t in enumerate(queue(ts, order), 1)]
        loose = [t["id"] for t in ts if t["id"] not in order]
        if loose:
            lines += ["", "Not in the Order list yet (sorted by number within their priority): " + ", ".join(loose)]
        return "\n".join(lines)
    lanes, placed, rows = b.lanes(plan), set(), []
    for lane, ids in lanes:
        ids = [i for i in dict.fromkeys(ids) if i in by_id]
        placed.update(ids)
        if ids:
            rows.append(f"- {lane}: " + " -> ".join(f"{i} {by_id[i]['state']}" for i in ids))
    loose = [t["id"] for t in ts if t["id"] not in placed]
    if lanes and loose:
        rows.append("- not in a lane: " + ", ".join(loose))
    if rows:
        lines += ["", "**Lanes, in order** (open tasks only; first = next to run):"] + rows
    return "\n".join(lines)


def next_view(b, ts, plan, n=3):
    """What's next, as plain text: the questions waiting on the user, then the first n of the queue (or each lane's
    first open task)."""
    by_id = {t["id"]: t for t in ts}
    lines = ["Waiting on you:"] + [f"  {t['id']}: {t['needs']}" for t in ts if t["needs"]] or ["  nothing"]
    order = b.order(plan)
    if order is not None:
        lines.append("Next:")
        lines += [f"  {k}. {t['priority'] or '—'} {t['id']} {t['title']} [{t['status']}]"
                  for k, t in enumerate(queue(ts, order)[:n], 1)]
    else:
        firsts = [(lane, next((by_id[i] for i in ids if i in by_id), None)) for lane, ids in b.lanes(plan)]
        lines.append("Next per lane:")
        lines += [f"  {lane}: {t['id']} {t['title']} [{t['status']}]" for lane, t in firsts if t]
        if not b.lanes(plan):
            lines += [f"  {t['id']} {t['title']} [{t['status']}]" for t in ts[:n]]
    return "\n".join(lines)


def done_block(cs):
    rows = ["| ID | Task | Closed | Resolution |", "|---|---|---|---|"]
    rows += [f"| [{c['id']}]({c['file']}) | {cell(c['title'])} | {c['closed']} | {cell(c['summary'])} |" for c in cs]
    return "\n".join(rows)


def replace(text, block, name):
    m = START.search(text)
    e = text.find(END, m.end()) if m else -1
    if e < 0:
        raise SystemExit(f"{name}: no {NEW_START} ... {END} block")
    return text[:m.start()] + f"{m.group(0)}\n{block}\n" + text[e:]


def main(argv):
    check = "--check" in argv
    root = project_root(argv)
    b = Board(root, config(root))
    if not b.index.is_file():
        print(f"{b.index}: no task index (habits.json tasks.dir / tasks.index)")
        return 1
    ts, problems = b.open_tasks()
    cs = b.closed_tasks()
    plan = b.plan.read_text(encoding="utf-8") if b.plan and b.plan.is_file() else None
    open_ids, closed_ids = {t["id"] for t in ts}, {c["id"] for c in cs}
    for lane, ids in b.lanes(plan or ""):
        problems += [f"{b.plan.name} lane {lane}: {i} is closed (in {b.done.name}/), take it out of the lane"
                     for i in ids if i in closed_ids]
        problems += [f"{b.plan.name} lane {lane}: {i} is no task file" for i in ids if i not in open_ids | closed_ids]
    for i in b.order(plan or "") or []:
        if i in closed_ids:
            problems.append(f"{b.plan.name} Order: {i} is closed (in {b.done.name}/), take it out of the list")
        elif i not in open_ids:
            problems.append(f"{b.plan.name} Order: {i} is no task file")
    since = config(root).get("review_since")
    if since:
        problems += [f"{b.done.name}/{c['file']}: closed {c['closed']} with no review line in its Resolution "
                     f"(`Review: <link / result>`, or `Review: none (<why>)`)"
                     for c in cs if c["closed"] != "—" and c["closed"] >= since and not c["reviewed"]]
    if "--next" in argv:
        print(next_view(b, ts, plan or ""))
        for p in problems:
            print(p)
        return 0
    targets = [(b.index, lambda: index_block(ts))]
    if plan is not None:
        rel = os.path.relpath(b.dir, b.plan.parent).replace("\\", "/")
        link_dir = "" if rel == "." else rel + "/"
        targets.append((b.plan, lambda: plan_block(b, ts, plan, link_dir)))
    if b.done_list.is_file():
        targets.append((b.done_list, lambda: done_block(cs)))
    stale = []
    for path, build in targets:
        text = path.read_text(encoding="utf-8")
        name = path.relative_to(root).as_posix()
        new = replace(text, build(), name)
        if new != text:
            stale.append(name)
            if not check:
                path.write_text(new, encoding="utf-8", newline="\n")
    try:   # after the rewrite, so a stale board's rows don't count
        lists = (json.loads((root / ".claude" / "habits.json").read_text(encoding="utf-8")).get("trackers")
                 or {}).get("lists") or []
    except (OSError, ValueError):
        lists = []
    problems += b.broken_links(root, lists)
    for p in problems:
        print(p)
    if check and stale:
        print(f"stale board in {', '.join(stale)}: run python -I tools/tasks.py")
    elif stale:
        print(f"rewrote {', '.join(stale)}")
    return 1 if problems or (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
